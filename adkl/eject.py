#!/usr/bin/env python3
"""adkl eject — export supported agents or inspect an incomplete scaffold.

Active unwired features and unsupported agent components block normal export.
Explicit --scaffold output contains an execution guard before runtime imports.

## Why this exists at all

AWS's Bedrock Agents Classic is the cautionary case: what made it a dead end was
not the config format but the **closed orchestration loop** -- only
`promptOverrideConfiguration` was exposed, so when config was not enough there
was nowhere to go. Its replacement pitches the opposite: *"export to Strands
code ... when configuration isn't enough."*

So the eject path is a first-class feature here, not an admission of failure.
`agent.yaml` requires `eject.target`, and this module is what honours it.

## The contract, and how it changed

Originally the output imported nothing from adk-lightning, because everything was
resolved at compile time. Porting the retrieval runtime (`adkl.retrieval`)
changed that: the mechanism is ~600 lines of real behaviour, and inlining it
would emit generated code nobody would read or trust.

So the escape hatch is now **from the config, not from the library**. Ejected
code imports `adkl.retrieval` for the feature runtime and `adkl.gateway` for the
model construction (which provider, and the thinking forwarding ADK drops on the
LiteLLM path), but is otherwise plain ADK:
you get an ordinary Python file you can edit, diff and step through, with no
`agent.yaml` in the loop. `--standalone` is the intended future option for a true
clean break; it does not exist yet, and the header says so rather than implying
a guarantee that is not there.

One-way by design either way: there is no import-back. Round-tripping generated
code is what makes these tools rot (MDA/QVT; Microsoft deprecating
`pac canvas pack/unpack` in favour of a read-only format).

## What is generated

* a compiled `InstructionProvider` with named slots already substituted, doing
  its own `{state_key}` interpolation (a callable instruction sets
  `bypass_state_injection=True`, so ADK will not do it for you)
* the skill list, loaded from disk by name
* resolved feature constants, with unwired callbacks called out
* an `LlmAgent` and an `App`

Tool bindings are not yet exported. Configurations requiring them can only be
inspected as non-executable scaffolds until the shared runtime factory exists.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sys
import textwrap
from typing import Any

import yaml

if __package__:
    from . import features as features_mod
    from . import instruction as instruction_mod
else:  # pragma: no cover -- script mode
    sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
    from adkl import features as features_mod
    from adkl import instruction as instruction_mod


HEADER = '''\
# GENERATED BY `adkl eject` -- DO NOT EDIT.
#
# Regenerate with:
#     python3 -m adkl.eject {source}
#
# Plain ADK plus `adkl.retrieval` for the feature runtime. Editing this file is
# fine -- it is ordinary Python -- but hand edits are lost on the next eject.
# To change behaviour, edit {source} and regenerate; to leave the
# config layer for good, keep this file and stop regenerating.
#
# Source of truth: {source}
# Agent:           {agent_name}
# Skills:          {skill_count}
# Features:        {feature_list}
'''


def _py(value: Any) -> str:
    """Render a Python literal. json.dumps is close but emits JS keywords."""
    if isinstance(value, bool):
        return "True" if value else "False"
    if value is None:
        return "None"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return repr(value)
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(_py(v) for v in value) + "]"
    if isinstance(value, dict):
        return "{" + ", ".join(f"{_py(k)}: {_py(v)}" for k, v in value.items()) + "}"
    return repr(value)


def generate(agent_yaml: pathlib.Path,
             target: pathlib.Path | None = None, *, scaffold: bool = False) -> str:
    from adkl import capabilities

    root = agent_yaml.parent
    doc = yaml.safe_load(agent_yaml.read_text(encoding="utf-8")) or {}
    agent = doc.get("agent") or {}
    inst = agent.get("instruction") or {}

    # ---- instruction: compile now, so the generated file carries the finished
    # text rather than re-reading block files at import time.
    slots = []
    for name, spec in (inst.get("slots") or {}).items():
        if isinstance(spec, str):
            slots.append(instruction_mod.Slot(name, pathlib.Path(spec)))
        else:
            slots.append(instruction_mod.Slot(
                name,
                variants={k: pathlib.Path(v)
                          for k, v in (spec.get("variants") or {}).items()},
                select=spec.get("select")))
    compiled = instruction_mod.compile_instruction(
        root / inst["template"], root, slots)

    resolved = features_mod.resolve(doc.get("features"))
    blockers = capabilities.export_report(doc)["blockers"]
    unsupported = "Export is incomplete:\n" + "\n".join(blockers)
    if blockers and not scaffold:
        raise features_mod.FeatureError(unsupported + "\nUse --scaffold only to inspect incomplete code.")
    retrieval_cfg = resolved.config.get("skill_retrieval")
    skills = list((doc.get("skills") or {}).get("include") or [])
    skills_dir = (doc.get("skills") or {}).get("dir") or "skills"
    retrieval = doc.get("retrieval") or {}

    # Relative hop from the generated file back to the config root. eject.target
    # is usually a generated/ subdirectory, so the skills path in the emitted
    # code cannot be relative to the file itself.
    up = "."
    if target is not None:
        try:
            rel = target.resolve().parent.relative_to(root.resolve())
            up = "/".join([".."] * len(rel.parts)) or "."
        except ValueError:
            up = "."

    out: list[str] = [HEADER.format(
        source=agent_yaml.name,
        agent_name=agent.get("name", "?"),
        skill_count=len(skills),
        feature_list=", ".join(resolved.active) or "(none)",
    )]

    out.append(textwrap.dedent('''
        from __future__ import annotations

        {execution_guard}

        import pathlib
        import re

        from google.adk.agents import LlmAgent
        from google.adk.apps import App
        from google.adk.skills import load_skill_from_dir

        from adkl.gateway import GatewaySettings, build_model, read_env

        _HERE = pathlib.Path(__file__).resolve().parent
        # Skills live beside agent.yaml, which may be a parent of this file:
        # eject.target is usually a generated/ subdirectory.
        _ROOT = (_HERE / {up}).resolve()
        _SKILLS = _ROOT / {skills_dir}
    ''').format(skills_dir=_py(skills_dir), up=_py(up),
                execution_guard=("raise RuntimeError(" + repr(unsupported) + ")"
                                 if blockers else "")))

    # ---- the instruction provider
    out.append('''
# ---------------------------------------------------------------- instruction

# Named slots are already substituted. What remains is runtime state, which this
# provider interpolates itself: ADK sets bypass_state_injection=True for a
# callable instruction (llm_agent.py: canonical_instruction), so it will NOT run
# inject_session_state for us.
_PROMPT = """\\
''' + compiled.text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"') + '"""\n')

    out.append(textwrap.dedent('''
        # ADK's rule, from _is_valid_state_name: a bare identifier or one of the
        # three scope prefixes plus an identifier. Anything else is emitted
        # verbatim -- which is why the validator rejects those at config time.
        _STATE_NAME = re.compile(r"^(app:|user:|temp:)?[A-Za-z_][A-Za-z0-9_]*$")
        _PLACEHOLDER = re.compile(r"{+[^{}]*}+")


        def _instruction(ctx) -> str:
            """InstructionProvider. Mirrors ADK's own regex engine."""
            state = getattr(ctx, "state", None)
            if state is None:
                inv = getattr(ctx, "_invocation_context", None)
                state = getattr(getattr(inv, "session", None), "state", {}) or {}

            def sub(m):
                name = m.group().lstrip("{").rstrip("}").strip()
                optional = name.endswith("?")
                if optional:
                    name = name[:-1]
                if not _STATE_NAME.match(name):
                    return m.group()
                if name in state:
                    value = state[name]
                    return "" if value is None else str(value)
                if optional:
                    return ""
                raise KeyError(
                    "Context variable not found: `%s` in agent '%s'"
                    % (name, getattr(ctx, "agent_name", "agent")))

            return _PLACEHOLDER.sub(sub, _PROMPT)
    '''))

    # ---- state contract, as a comment the reader can act on
    if compiled.required_state or compiled.optional_state:
        out.append("\n# State this prompt reads:")
        for k in compiled.required_state:
            out.append(f"#   {k:38} REQUIRED -- absent raises KeyError")
        for k in compiled.optional_state:
            out.append(f"#   {k:38} optional -- absent renders empty")
        out.append("")

    # ---- skills
    out.append(textwrap.dedent('''
        # --------------------------------------------------------------------- skills

        # Explicit list, in order. A new directory does not silently join the
        # agent -- that is the config drift the linter exists to catch.
        SKILL_NAMES = {skills}

        SKILLS = [load_skill_from_dir(_SKILLS / name) for name in SKILL_NAMES]
    ''').format(skills=_py(skills)))

    # ---- features
    out.append("\n# ------------------------------------------------------------------- features\n")
    if not resolved.active:
        out.append("# No features active in features.pipeline.\n")
    for name in resolved.active:
        spec = features_mod.REGISTRY[name]
        cfg = resolved.config.get(name, {})
        out.append(f"# {name}  [{spec.kind.value}, {spec.stage.value}]")
        out.append(f"#   {spec.summary}")
        if spec.may_short_circuit:
            out.append("#   NOTE: halts its hook when it fires, so later "
                       "callbacks on that")
            out.append("#   hook -- including any you add by hand -- will not run.")
        out.append(f"{name.upper()}_CONFIG = {_py(cfg)}")
        out.append("")

    if "skill_retrieval" in resolved.active:
        vectors = (retrieval_cfg or {}).get("vectors", "embeddings/skills.json")
        out.append(textwrap.dedent('''
            from adkl.retrieval import (
                SkillRetrieval, config_from_dict, load_vectors,
            )

            # Precomputed skill-description vectors. Rebuild these whenever a
            # description changes: retrieval matches the OLD text until you do,
            # which is silent and looks like a bad model.
            #
            # Loaded lazily. Eager loading meant a missing vector file killed the
            # whole module at import, so the agent could not be built at all --
            # retrieval is an optimization and its absence must not do that.
            _VECTOR_PATH = _ROOT / {vectors}
            _VECTORS = None


            def vectors():
                """Load once. Raises only when retrieval is actually used."""
                global _VECTORS
                if _VECTORS is None:
                    _VECTORS = load_vectors(_VECTOR_PATH)
                    model = SKILL_RETRIEVAL_CONFIG.get("embedding_model", "")
                    if _VECTORS.backend and _VECTORS.backend not in model:
                        import warnings as _w
                        _w.warn(
                            "vector file was built by backend %r but the "
                            "configured model is %r. Cosine similarity returns "
                            "meaningless numbers across backends rather than "
                            "failing." % (_VECTORS.backend, model), stacklevel=2)
                return _VECTORS

            # Supply an embedder: anything with `async def embed(text) -> list[float]`.
            # Left to the host project because it carries the credentials.
            RETRIEVAL = None   # SkillRetrieval(
            #     config_from_dict(SKILL_RETRIEVAL_CONFIG),
            #     vectors().vectors, my_embedder, vectors().descriptions)
        ''').format(vectors=_py(vectors)))

    out.append(textwrap.dedent('''
        # TODO(eject): the remaining feature configs above are resolved but not
        # wired. history_slicing wants a before_model_callback,
        # tool_result_trimming an after_tool_callback, never a runner plugin.
        # Their configs are validated and ordered; the callbacks are yours to
        # attach.
    '''))

    # ---- the agent
    #
    # The model is BUILT, not named. Emitting the bare id was wrong in a way
    # that looks fine: ADK would resolve `gemini-3.6-flash` natively and the
    # agent would answer, while silently bypassing the provider the running
    # agent uses -- a different client, different credentials, and on the
    # gateway path no thinking_config forwarding, which is the empty-reply bug.
    # An eject that quietly changes the backend is worse than no eject.
    model = agent.get("model", "gemini-2.5-flash")
    provider = agent.get("provider")
    out.append(textwrap.dedent('''
        # ---------------------------------------------------------------------- agent
        #
        # Same provider the agent.yaml declared. `.env` beside this file (or at
        # the adk-lightning root) supplies the credential; see adkl/gateway.py
        # for the variable names.

        _settings = GatewaySettings.from_env(
            read_env(pathlib.Path(__file__).resolve().parent),
            provider={provider},
        )

        root_agent = LlmAgent(
            name={name},
            model=build_model(_settings, {model}),
            instruction=_instruction,   # callable: see the note above
        )

        app = App(name={name}, root_agent=root_agent)
    ''').format(name=_py(agent.get("name", "agent")), model=_py(model),
               provider=_py(provider)))

    if retrieval:
        out.append("\n# Retrieval settings from agent.yaml, for whichever toolset")
        out.append("# you attach:")
        out.append(f"RETRIEVAL = {_py(retrieval)}\n")

    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description="Export supported ADK code or inspect an incomplete scaffold.")
    ap.add_argument("agent_yaml", type=pathlib.Path)
    ap.add_argument("-o", "--out", type=pathlib.Path,
                    help="defaults to eject.target from agent.yaml")
    ap.add_argument("--scaffold", action="store_true",
                    help="write incomplete code for inspection; execution is blocked")
    args = ap.parse_args()

    doc = yaml.safe_load(args.agent_yaml.read_text(encoding="utf-8")) or {}
    target = args.out
    if target is None:
        rel = (doc.get("eject") or {}).get("target")
        if not rel:
            print("error: no eject.target in agent.yaml and no --out given",
                  file=sys.stderr)
            return 2
        target = args.agent_yaml.parent / rel

    try:
        code = generate(args.agent_yaml, target, scaffold=args.scaffold)
    except (instruction_mod.SlotError, instruction_mod.TemplateError,
            features_mod.FeatureError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(code, encoding="utf-8")
    print(f"wrote {target}  ({len(code.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
